const assert=require('node:assert/strict'),fs=require('node:fs'),path=require('node:path');
const {pathToFileURL}=require('node:url');
const {chromium}=require(process.env.PLAYWRIGHT_MODULE||'playwright-core');
const {fixture}=require('./solver-browser-fixtures.cjs');
(async()=>{
 const browser=await chromium.launch({executablePath:process.env.CHROME_PATH||'C:/Program Files/Google/Chrome/Application/chrome.exe',headless:true});
 try {
  const context=await browser.newContext({acceptDownloads:true,viewport:{width:1440,height:1000}});
  const project=fixture({mode:'zero'});
  await context.addInitScript(p=>localStorage.setItem('scenario-workbench.project.v1',JSON.stringify(p)),project);
  const page=await context.newPage(),errors=[];page.on('pageerror',e=>errors.push(e.message));
  await page.goto(pathToFileURL(path.resolve('dist/scenario-workbench.html')).href);
  await page.locator('nav [data-route=solver]').first().click();
  await page.locator('.solver-fullspace button').filter({hasText:/^(开始检验|重新检验)$/}).click();
  await page.waitForFunction(()=>document.querySelector('[data-solver-summary]')?.textContent.includes('共找到 4 种自洽组合'));
  await page.locator('nav [data-route=robustness]').first().click();
  const before=await page.evaluate(()=>localStorage.getItem('scenario-workbench.project.v1'));
  const run=page.getByRole('button',{name:'联合重算并比较',exact:true});
  assert.equal(await run.isDisabled(),true);
  await page.getByLabel('新评分',{exact:true}).selectOption('1');
  await page.getByRole('button',{name:'加入联合改分',exact:true}).click();
  await page.getByRole('button',{name:'加入联合改分',exact:true}).click();
  assert.match(await page.locator('[data-joint-list]').innerText(),/已选择 1 项/);
  await page.getByLabel('要改的评分格',{exact:true}).selectOption('1');
  await page.getByLabel('新评分',{exact:true}).selectOption('1');
  await page.getByRole('button',{name:'加入联合改分',exact:true}).click();
  await run.click();
  const stats=await page.locator('.robust-stats b').allTextContents();
  assert.deepEqual(stats,['4','4','4','0','0']);
  const pending=page.waitForEvent('download');
  await page.getByRole('button',{name:'导出这次比较',exact:true}).click();
  const download=await pending,output=JSON.parse(fs.readFileSync(await download.path(),'utf8'));
  assert.equal(output.method,'joint-selected-cells');assert.equal(output.changes.length,2);
  assert.deepEqual(output.changes.map(c=>[c.previousScore,c.score]),[[0,1],[0,1]]);
  const {solve}=await import('../src/modules/solver/engine.mjs');
  assert.equal(solve(output.variantInput).count,4);
  assert.equal(await page.evaluate(()=>localStorage.getItem('scenario-workbench.project.v1')),before);
  if(process.env.JOINT_SHOT)await page.screenshot({path:process.env.JOINT_SHOT,fullPage:true});
  await page.getByRole('button',{name:'移除联合评分 0',exact:true}).click();
  assert.equal(await run.isDisabled(),true);
  assert.equal(await page.getByRole('button',{name:'导出这次比较',exact:true}).count(),0);
  await page.getByRole('button',{name:'清空联合改分',exact:true}).click();
  assert.match(await page.locator('[data-joint-list]').innerText(),/已选择 0 项/);
  await page.setViewportSize({width:390,height:1000});
  assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth>innerWidth+1),false);
  assert.deepEqual(errors,[]);
  await context.close();console.log('PASS joint browser: selection, deduplication, full set cancellation, actual JSON replay, input unchanged, removal invalidation, clear, mobile');
 } finally {await browser.close();}
})().catch(e=>{console.error(e);process.exitCode=1;});
