const assert = require('node:assert/strict');
const path = require('node:path');
const fs = require('node:fs/promises');
const { pathToFileURL } = require('node:url');
const { chromium } = require(process.env.PLAYWRIGHT_MODULE || 'playwright');

(async () => {
  const root = path.resolve(__dirname, '..');
  const out = path.join(root, 'artifacts');
  await fs.mkdir(out, { recursive: true });
  const browser = await chromium.launch({ executablePath: process.env.CHROME_PATH || 'C:/Program Files/Google/Chrome/Application/chrome.exe', headless: true, args: ['--no-sandbox', '--disable-gpu'] });
  const results = [];
  try {
    for (const [mode, url] of [['source', process.env.APP_URL || 'http://127.0.0.1:4173'], ['offline', pathToFileURL(path.join(root, 'dist/scenario-workbench.html')).href]]) {
      const context = await browser.newContext({ viewport: { width: 1440, height: 1080 }, acceptDownloads: true });
      const page = await context.newPage(), errors = [], external = [];
      page.on('pageerror', error => errors.push(error.message));
      page.on('request', request => { if (/^https?:/.test(request.url()) && !request.url().startsWith('http://127.0.0.1:')) external.push(request.url()); });
      page.on('dialog', dialog => dialog.accept());
      await page.goto(url);
      await page.getByLabel('项目名称', { exact: true }).fill('第一包验证项目');
      await page.getByLabel('研究地区', { exact: true }).fill('京津冀');
      await page.getByLabel('研究年份', { exact: true }).fill('2026, 2030');
      await page.getByRole('button', { name: '保存项目范围', exact: true }).click();
      await page.getByRole('button', { name: '记录未检验快照', exact: true }).click();
      assert.match(await page.locator('#snapshot-details').innerText(), /当前输入/);
      await page.getByRole('combobox', { name: '界面视角', exact: true }).selectOption('expert');
      assert.match(await page.locator('.context-panel').innerText(), /科学修订 1/);
      await page.getByLabel('研究年份', { exact: true }).fill('2035');
      await page.getByRole('button', { name: '保存项目范围', exact: true }).click();
      assert.match(await page.locator('#snapshot-details').innerText(), /已过期/);
      await page.getByLabel('研究年份', { exact: true }).fill('2030, 2030');
      await page.getByLabel('项目名称', { exact: true }).fill('不应半保存');
      await page.getByRole('button', { name: '保存项目范围', exact: true }).click();
      assert.match(await page.locator('form .message').innerText(), /不重复/);
      assert.match(await page.locator('.facts').innerText(), /第一包验证项目/);
      await page.getByRole('button', { name: '载入机制示例', exact: true }).click();
      assert.match(await page.locator('.facts').innerText(), /2 个分类节点 · 2 个计算变量/);
      await page.getByRole('combobox', { name: '界面视角', exact: true }).selectOption('public');
      await page.getByRole('combobox', { name: '界面视角', exact: true }).selectOption('expert');
      assert.match(await page.locator('.facts').innerText(), /2 个分类节点 · 2 个计算变量/);
      const downloadEvent = page.waitForEvent('download');
      await page.getByRole('button', { name: '下载项目备份', exact: true }).click();
      const download = await downloadEvent;
      const backup = JSON.parse(await fs.readFile(await download.path(), 'utf8'));
      assert.equal(backup.contractVersion, '1.0.0');
      assert.equal(backup.data.judgments.length, 0);
      const invalid = Buffer.from(JSON.stringify({ schemaVersion: 999 }));
      await page.getByLabel('从JSON备份恢复').setInputFiles({ name: 'invalid.json', mimeType: 'application/json', buffer: invalid });
      await page.waitForFunction(() => document.querySelector('form .message')?.textContent.includes('备份未载入'));
      assert.match(await page.locator('form .message').innerText(), /备份未载入/);
      await page.getByLabel('从JSON备份恢复').setInputFiles({ name: 'valid.json', mimeType: 'application/json', buffer: Buffer.from(JSON.stringify(backup)) });
      await page.waitForFunction(() => document.querySelector('#global-status')?.textContent.includes('已恢复'));
      assert.match(await page.locator('#global-status').innerText(), /已恢复/);
      await page.reload();
      assert.match(await page.locator('.facts').innerText(), /六层选择机制示例/);
      await page.screenshot({ path: path.join(out, mode + '-desktop.png'), fullPage: true });
      await page.locator('[data-route="elements"]').click();
      assert.match(await page.locator('#module-content').innerText(), /描述符多级选择/);
      await page.getByRole('button', { name: '清空选择', exact: true }).click();
      await page.locator('[data-node="node-1"]').check();
      assert.match(await page.locator('.elements-summary').innerText(), /待配置/);
      assert.match(await page.locator('.facts').innerText(), /1 个分类节点 · 0 个计算变量/);
      await page.reload();
      assert.equal(await page.locator('[data-node="node-1"]').isChecked(), true);
      await page.getByRole('button', { name: '方法与实现进度', exact: true }).click();
      assert.match(await page.locator('.formula').innerText(), /一致性条件/);
      await page.screenshot({ path: path.join(out, mode + '-methods.png'), fullPage: true });
      await page.locator('[data-route="workspace"]').click();
      await page.setViewportSize({ width: 390, height: 844 });
      assert.equal(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), true);
      await page.screenshot({ path: path.join(out, mode + '-mobile.png'), fullPage: true });
      assert.deepEqual(errors, []);
      assert.deepEqual(external, []);
      results.push({ mode, passed: true, pageErrors: errors, externalRequests: external });
      await context.close();
    }
    const failureContext = await browser.newContext();
    const failurePage = await failureContext.newPage();
    await failurePage.addInitScript(() => { Storage.prototype.setItem = function () { throw new Error('simulated storage quota failure'); }; });
    await failurePage.goto(process.env.APP_URL || 'http://127.0.0.1:4173');
    await failurePage.getByLabel('项目名称', { exact: true }).fill('仅在内存中的项目');
    await failurePage.getByRole('button', { name: '保存项目范围', exact: true }).click();
    assert.match(await failurePage.locator('.storage-status').innerText(), /浏览器保存失败/);
    assert.match(await failurePage.locator('form .message').innerText(), /当前页面/);
    assert.match(await failurePage.locator('#global-status').innerText(), /尚未保存到浏览器/);
    await failurePage.screenshot({ path: path.join(out, 'storage-failure.png'), fullPage: true });
    await failureContext.close();
    const mixedContext = await browser.newContext();
    const mixedPage = await mixedContext.newPage();
    await mixedPage.goto(process.env.APP_URL || 'http://127.0.0.1:4173');
    const sampleContext = await browser.newContext();
    const samplePage = await sampleContext.newPage();
    await samplePage.goto(process.env.APP_URL || 'http://127.0.0.1:4173');
    samplePage.on('dialog', dialog => dialog.accept());
    await samplePage.getByRole('button', { name: '载入机制示例', exact: true }).click();
    const sample = await samplePage.evaluate(() => JSON.parse(localStorage.getItem('scenario-workbench.project.v1')));
    Object.values(sample.data).flat().forEach(record => { record.provenance.origin = 'import'; if (record.kind === 'fixture') record.kind = 'user-assumption'; });
    sample.data.judgments = [{ id: 'ab', version: 1, provenance: { origin: 'import' }, sourceDescriptorId: 'descriptor-a', targetDescriptorId: 'descriptor-b', entries: [], evidenceRefs: [] }];
    mixedPage.on('dialog', dialog => dialog.accept());
    await mixedPage.getByLabel('从JSON备份恢复').setInputFiles({ name: 'imported.json', mimeType: 'application/json', buffer: Buffer.from(JSON.stringify(sample)) });
    await mixedPage.waitForFunction(() => document.querySelector('#global-status').textContent.includes('已恢复'));
    assert.match(await mixedPage.locator('.context-panel').innerText(), /用户或导入记录/);
    assert.match(await mixedPage.locator('.context-panel').innerText(), /影响判断：1 条/);
    assert.doesNotMatch(await mixedPage.locator('.context-panel').innerText(), /全部数据为软件机制示例/);
    await mixedPage.screenshot({ path: path.join(out, 'imported-source-summary.png'), fullPage: true });
    await mixedContext.close();
    await sampleContext.close();
    results.push({ mode: 'edge-cases', passed: true, checks: ['persistent storage failure message', 'imported provenance summary and judgment count'] });
    await fs.writeFile(path.join(out, 'browser-results.json'), JSON.stringify(results, null, 2));
    console.log('Browser smoke passed: source + offline; persistence, view, stale snapshot, atomic validation, backup restore, placeholders, responsive layout.');
  } finally { await browser.close(); }
})().catch(error => { console.error(error); process.exitCode = 1; });
