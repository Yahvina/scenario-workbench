const assert = require('node:assert/strict');
const path = require('node:path');
const fs = require('node:fs/promises');
const { pathToFileURL } = require('node:url');
const { chromium } = require(process.env.PLAYWRIGHT_MODULE || 'playwright');

(async () => {
  const root = path.resolve(__dirname, '..'), out = path.join(root, 'artifacts/neutral');
  await fs.mkdir(out, { recursive: true });
  const browser = await chromium.launch({ executablePath: process.env.CHROME_PATH || 'C:/Program Files/Google/Chrome/Application/chrome.exe', headless: true, args: ['--no-sandbox', '--disable-gpu'] });
  const evidence = [];
  try {
    for (const [mode, url] of [['source', (process.env.APP_URL || 'http://127.0.0.1:4173') + '/design/neutral-workbench.html'], ['offline', pathToFileURL(path.join(root, 'dist/neutral-workbench.html')).href]]) {
      const context = await browser.newContext({ viewport: { width: 1560, height: 1100 } });
      const page = await context.newPage(), errors = [], external = [];
      page.on('pageerror', error => errors.push(error.message));
      page.on('request', request => { if (/^https?:/.test(request.url()) && !request.url().startsWith('http://127.0.0.1:')) external.push(request.url()); });
      await page.goto(url);
      const view = page.getByRole('combobox', { name: '界面视角', exact: true });
      await view.selectOption('expert');
      await view.selectOption('public');
      await page.getByRole('button', { name: '展开 能源系统', exact: true }).click();
      await page.getByRole('button', { name: '展开 能源供给', exact: true }).click();
      const state = () => page.evaluate(() => JSON.parse(localStorage.getItem('scenario-workbench.neutral-sample.v1')));
      const before = await state();
      const save = page.getByRole('button', { name: '保存路径', exact: true });
      const style = locator => locator.evaluate(node => { const s = getComputedStyle(node); return { background: s.backgroundColor, border: s.borderTopColor, color: s.color, outline: s.outlineWidth, outlineStyle: s.outlineStyle, weight: s.fontWeight }; });
      const surfaces = await page.locator('.topbar,.sidebar,.surface').evaluateAll(nodes => nodes.map(node => getComputedStyle(node).backgroundColor));
      assert.equal(surfaces.every(value => value === 'rgb(255, 255, 255)'), true);
      await page.mouse.move(1, 1);
      const normal = await style(save);
      assert.equal(normal.background, 'rgb(255, 255, 255)');
      assert.equal(normal.weight, '600');
      assert.equal((await style(page.locator('.elements-row.is-selected'))).background, 'rgb(236, 238, 241)');
      const variableColors = await page.evaluate(() => ({ left: getComputedStyle(document.querySelector('.elements-summary .variable-mark')).backgroundColor, right: getComputedStyle(document.querySelector('#path-panel .variable-mark')).backgroundColor, curve: getComputedStyle(document.querySelector('.sample-graph .curve')).stroke }));
      assert.equal(variableColors.left, variableColors.right);
      assert.equal(variableColors.right, variableColors.curve);
      await page.screenshot({ path: path.join(out, mode + '-default-selected.png'), fullPage: true });
      await save.hover();
      await page.waitForFunction(() => getComputedStyle(document.querySelector('#save-sample-path')).backgroundColor === 'rgb(242, 243, 245)');
      const hover = await style(save);
      assert.notEqual(hover.background, normal.background);
      assert.notEqual(hover.border, normal.border);
      await page.screenshot({ path: path.join(out, mode + '-hover.png'), fullPage: true });
      await page.mouse.down();
      await page.waitForFunction(() => getComputedStyle(document.querySelector('#save-sample-path')).backgroundColor === 'rgb(231, 233, 236)');
      const pressed = await style(save);
      assert.notEqual(pressed.background, hover.background);
      await page.screenshot({ path: path.join(out, mode + '-pressed.png'), fullPage: true });
      await page.mouse.move(1, 1);
      await page.mouse.up();
      await page.getByRole('button', { name: '取消修改', exact: true }).focus();
      await page.keyboard.press('Tab');
      assert.equal(await save.evaluate(node => node === document.activeElement), true);
      const focus = await style(save);
      assert.equal(focus.outline, '2px');
      assert.equal(focus.outlineStyle, 'solid');
      await page.screenshot({ path: path.join(out, mode + '-focus.png'), fullPage: true });
      await page.getByRole('spinbutton', { name: '节点2年份', exact: true }).fill('2026');
      await save.click();
      assert.match(await page.locator('#path-panel').innerText(), /错误：年份重复/);
      assert.equal(await page.getByRole('spinbutton', { name: '节点2年份', exact: true }).getAttribute('aria-invalid'), 'true');
      assert.equal((await style(page.getByRole('spinbutton', { name: '节点2年份', exact: true }))).border, 'rgb(156, 52, 56)');
      assert.deepEqual((await state()).data.paths, before.data.paths);
      await page.screenshot({ path: path.join(out, mode + '-error.png'), fullPage: true });
      await page.getByRole('spinbutton', { name: '节点2年份', exact: true }).fill('2030');
      await page.getByRole('spinbutton', { name: '节点2力度', exact: true }).fill('52');
      await save.click();
      assert.equal((await state()).data.paths[0].points[1].value, 52);
      assert.match(await page.locator('.sample-graph').textContent(), /52/);
      assert.match(await page.locator('#sample-page-status').innerText(), /仍未检算/);
      assert.equal(await page.locator('.matrix-zero').innerText(), '0 · 无关系');
      assert.equal(await page.locator('.matrix-missing').innerText(), '未判断');
      assert.equal(await page.locator('.matrix-missing').evaluate(node => getComputedStyle(node).outlineStyle), 'dashed');
      assert.notEqual((await style(page.locator('.matrix-zero'))).background, (await style(page.locator('.matrix-missing'))).background);
      await page.reload();
      assert.equal(await page.getByRole('spinbutton', { name: '节点2力度', exact: true }).inputValue(), '52');
      await page.setViewportSize({ width: 390, height: 844 });
      assert.equal(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), true);
      await page.screenshot({ path: path.join(out, mode + '-mobile.png'), fullPage: true });
      assert.deepEqual(errors, []); assert.deepEqual(external, []);
      evidence.push({ mode, normal, hover, pressed, focus, variableColors, surfaces, errors, external });
      await context.close();
      const appContext = await browser.newContext({ viewport: { width: 1440, height: 1080 } });
      const appPage = await appContext.newPage();
      await appPage.goto(mode === 'source' ? (process.env.APP_URL || 'http://127.0.0.1:4173') : pathToFileURL(path.join(root, 'dist/scenario-workbench.html')).href);
      await appPage.locator('[data-route="elements"]').click();
      await appPage.getByRole('button', { name: '使用已有京津冀框架（24项）' }).click();
      await appPage.getByRole('button', { name: '展开 能源供给', exact: true }).click();
      await appPage.getByLabel('可再生价格干预强度', { exact: true }).check();
      const appMark = await appPage.locator('.elements-summary .variable-mark').first().evaluate(node => getComputedStyle(node).backgroundColor);
      assert.equal(appMark, variableColors.curve);
      const appSurfaces = await appPage.locator('.topbar,.sidebar,.surface').evaluateAll(nodes => nodes.map(node => getComputedStyle(node).backgroundColor));
      assert.equal(appSurfaces.every(color => color === 'rgb(255, 255, 255)'), true);
      const selectedNav = await appPage.locator('.nav-item[aria-current="page"]').evaluate(node => ({ background: getComputedStyle(node).backgroundColor, weight: getComputedStyle(node).fontWeight, marker: getComputedStyle(node, '::before').width }));
      assert.deepEqual(selectedNav, { background: 'rgb(236, 238, 241)', weight: '600', marker: '1px' });
      await appPage.screenshot({ path: path.join(out, mode + '-app-propagation.png'), fullPage: true });
      await appContext.close();
      console.log(mode + ': white surfaces, neutral buttons, hover/pressed/focus, selection, errors, atomic save, object colors, matrix missing and mobile passed');
    }
    await fs.writeFile(path.join(out, 'audit.json'), JSON.stringify(evidence, null, 2));
  } finally { await browser.close(); }
})().catch(error => { console.error(error); process.exitCode = 1; });
