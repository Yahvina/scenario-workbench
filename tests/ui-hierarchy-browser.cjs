const assert=require('node:assert/strict'),fs=require('node:fs'),path=require('node:path');
const {pathToFileURL}=require('node:url');
const {chromium}=require(process.env.PLAYWRIGHT_MODULE||'playwright-core');
const {fixture}=require('./solver-browser-fixtures.cjs');
(async()=>{
 const browser=await chromium.launch({executablePath:process.env.CHROME_PATH||'C:/Program Files/Google/Chrome/Application/chrome.exe',headless:true});
 try{
  const context=await browser.newContext({acceptDownloads:true,viewport:{width:1440,height:1000}});
  const project=fixture({mode:'zero'});project.data.paths=[];
  await context.addInitScript(p=>localStorage.setItem('scenario-workbench.project.v1',JSON.stringify(p)),project);
  const page=await context.newPage(),errors=[];page.on('pageerror',e=>errors.push(e.message));
  await page.goto(process.env.APP_URL||pathToFileURL(path.resolve('dist/scenario-workbench.html')).href);
  const nav=route=>page.locator('nav [data-route="'+route+'"]').first().click();
  await nav('elements');
  assert.equal(await page.locator('[data-framework-catalog]').getAttribute('open'),null);
  await page.locator('[data-framework-catalog]>summary').focus();await page.keyboard.press('Enter');
  assert.equal(await page.locator('[data-framework-catalog]').evaluate(e=>e.open),true);
  await page.getByLabel('搜索描述符',{exact:true}).fill('x');
  assert.equal(await page.locator('[data-framework-catalog]').evaluate(e=>e.open),true);
  await nav('solver');
  assert.equal(await page.locator('.solver-plan-options').evaluate(e=>e.open),false);
  await page.locator('.solver-fullspace button').filter({hasText:/^开始检验$/}).click();
  await page.waitForFunction(()=>document.querySelector('[data-solver-summary]')?.textContent.includes('共找到 4 种'));
  assert(await page.locator('.solver-session').evaluate(e=>e.getBoundingClientRect().top<document.querySelector('.solver-scenarios').getBoundingClientRect().top));
  const downloadEvent=page.waitForEvent('download');
  await page.getByRole('button',{name:'下载本次结果 JSON',exact:true}).click();
  const downloaded=await downloadEvent,archive=JSON.parse(fs.readFileSync(await downloaded.path(),'utf8'));
  assert.equal(archive.RunResult.count,4);
  await page.locator('.solver-plan-options>summary').focus();await page.keyboard.press('Space');
  const state=page.locator('.plan-check select').first();
  await state.selectOption({index:1});
  assert.equal(await page.locator('.solver-plan-options').evaluate(e=>e.open),true);
  assert.equal(await page.locator('.plan-check select').count(),1);
  await page.locator('.plan-check select').first().selectOption({index:1});
  await page.getByRole('button',{name:'开始检验这份方案',exact:true}).click();
  await page.locator('.plan-check-rows-detail>summary').click();
  assert(await page.locator('.plan-check-table').isVisible());
  await page.locator('.solver-plan-options>summary').click();
  await page.getByRole('button',{name:'查看原因',exact:true}).click();
  assert.equal(await page.locator('.solver-plan-options').evaluate(e=>e.open),true);
  await nav('robustness');
  assert.equal(await page.locator('[data-joint-saved]').evaluate(e=>e.open),false);
  assert.equal(await page.locator('[data-batch-scan]').evaluate(e=>e.open),false);
  await page.locator('[data-batch-scan]>summary').click();
  await page.getByRole('button',{name:'扫描全部评分格',exact:true}).click();
  await page.locator('[data-batch-scan]>summary').click();
  assert(await page.locator('[data-batch-status]').isVisible());
  await page.waitForFunction(()=>document.querySelector('[data-batch-status]').textContent.includes('扫描完成'));
  await page.locator('[data-batch-scan]>summary').click();
  assert(await page.getByRole('button',{name:'导出扫描记录',exact:true}).isVisible());
  await page.setViewportSize({width:1024,height:768});
  assert(await page.locator('[data-joint-saved]>summary').isVisible());
  assert.deepEqual(errors,[]);
  console.log('UI hierarchy PASS: keyboard disclosure, rerender persistence, complete solve/download, inline plan check, reason link, scan status while folded, 1024px layout');
 }finally{await browser.close();}
})().catch(e=>{console.error(e);process.exitCode=1;});
